#!/usr/bin/env bash
# ==============================================================================
# slurm_status.sh - 查詢個人作業狀態、Nano4 叢集分區資源與可用度
# ==============================================================================
set -euo pipefail

USER_NAME="$(whoami)"

echo "========================================================"
echo "📊 [1/2] 個人排程中與執行中之作業 (squeue):"
echo "========================================================"
squeue -u "${USER_NAME}" -o "%.10i %.12P %.20j %.8T %.10M %.8D %.4C %R" || true

echo ""
echo "========================================================"
echo "🖥️ [2/2] Nano4 常用排程分區 (Partitions) 即時狀態:"
echo "========================================================"
echo ">> H200 / GB200 GPU 分區 與 NGS 生醫計算分區:"
sinfo -p dev,8gpus,gb200-dev,ngstest,ngs62g,ngs250g -o "%.14P %.10a %.10l %.10D %.12F %N" 2>/dev/null || sinfo -s

echo ""
echo "========================================================"
echo "常用指令速查:"
echo "   取消特定作業    : scancel <JOB_ID>"
echo "   取消個人所有作業: scancel -u ${USER_NAME}"
echo "   查看作業詳細資訊: scontrol show job <JOB_ID>"
echo "   查詢歷史資源消耗: seff <JOB_ID>"
echo "========================================================"
